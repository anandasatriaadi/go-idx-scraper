func toSnake(s string) string {
	re1 := regexp.MustCompile(`(.)([A-Z][a-z]+)`)
	re2 := regexp.MustCompile(`([a-z0-9])([A-Z])`)
	s = re1.ReplaceAllString(s, `${1}_${2}`)
	s = re2.ReplaceAllString(s, `${1}_${2}`)
	return strings.ToLower(s)
}

