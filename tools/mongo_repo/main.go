func extractImportPath(typeStr string) string {
	// Check if type contains a package selector (e.g., "time.Time" or "common.Something")
	if idx := strings.Index(typeStr, "."); idx > 0 {
		pkgName := typeStr[:idx]
		// Skip built-in types that don't need imports
		if pkgName == "time" {
			return ""
		}
		return pkgName
	}
	return ""
}

func collectImports(fields []Field, imports map[string]bool) {
	for _, field := range fields {
		// Remove pointer and slice prefixes to get base type
		baseType := field.Type
		baseType = strings.TrimPrefix(baseType, "*")
		baseType = strings.TrimPrefix(baseType, "[]")

		// Check if type contains a package path
		if strings.Contains(baseType, ".") {
			// Handle selector expressions like "time.Time" or "common.Status"
			parts := strings.Split(baseType, ".")
			if len(parts) >= 2 {
				pkgPath := strings.Join(parts[:len(parts)-1], ".")
				// Skip standard library packages that are already imported
				if pkgPath != "time" && pkgPath != "bson" {
					imports[pkgPath] = true
				}
			}
		}
	}
}

func fieldType(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + fieldType(t.X)
	case *ast.ArrayType:
		return "[]" + fieldType(t.Elt)
	case *ast.SelectorExpr:
		return fieldType(t.X) + "." + t.Sel.Name
	case *ast.MapType:
		return "map[" + fieldType(t.Key) + "]" + fieldType(t.Value)
	default:
		return "interface{}"
	}
}

func parseTag(f *ast.Field, name string) string {
	if f.Tag == nil {
		return ""
	}
	tag := strings.Trim(f.Tag.Value, "`")
	for part := range strings.FieldsSeq(tag) {
		val, ok := strings.CutPrefix(part, name+":")
		if !ok {
			continue
		}
		val = strings.Trim(val, "\"")
		before, _, found := strings.Cut(val, ",")
		if found {
			return before
		}
		return val
	}
	return ""
}

func collectFileImports(f *ast.File) map[string]string {
	// Map from package name to import path
	imports := make(map[string]string)
	for _, imp := range f.Imports {
		path := strings.Trim(imp.Path.Value, "\"")
		var name string
		if imp.Name != nil {
			name = imp.Name.Name
		} else {
			// Extract package name from path
			parts := strings.Split(path, "/")
			name = parts[len(parts)-1]
		}
		imports[name] = path
	}
	return imports
}

